import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
import {_electron as electron} from 'playwright';
const root=path.resolve('.'),out=await fs.mkdtemp(path.join(root,'test-output','image-row-operations-'));
const env={...process.env,ZIYUN_DATA_DIR:path.join(out,'data'),ZIYUN_SMOKE:'1'};delete env.ELECTRON_RUN_AS_NODE;
const executablePath=process.env.ZIYUN_TEST_EXE||createRequire(import.meta.url)('electron');
const launch=()=>electron.launch({executablePath,args:process.env.ZIYUN_TEST_EXE?[]:[root],env,timeout:60000});
let application=await launch(),page=await application.firstWindow();page.setDefaultTimeout(15000);
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const call=(method,...args)=>page.evaluate(({method,args})=>window.studio.call(method,...args),{method,args});
const wait=async predicate=>{const deadline=Date.now()+10000;while(Date.now()<deadline){const state=await call('getState');if(predicate(state))return state;await new Promise(resolve=>setTimeout(resolve,50))}throw Error('State timeout');};
try{
 await page.getByTestId('add-row').click();let state=await wait(s=>s.rows.length===1);
 assert.equal(state.rows[0].code,'A01');
 await call('saveRow',{...state.rows[0],name:'保留任务',code:'B01'});
 await page.getByTestId('add-row').click();state=await wait(s=>s.rows.length===2);
 assert.equal(state.rows[1].code,'B02');
 await call('saveRow',{...state.rows[1],name:'删除任务'});
 await page.getByTestId('add-row').click();state=await wait(s=>s.rows.length===3);
 assert.equal(state.rows[2].code,'B03');
 await call('saveRow',{...state.rows[2],name:'隐藏任务'});
 await page.getByLabel('编辑 保留任务',{exact:true}).click();
 await page.getByLabel('用户要求',{exact:true}).fill('未保存但需要保留的要求');
 await page.getByLabel('搜索任务编号或名称',{exact:true}).fill('删除任务');
 assert.equal(await page.locator('.task-table tbody tr').count(),1);
 await page.getByTestId('delete-rows').click();
 const single=page.getByRole('dialog',{name:'删除素材类型',exact:true});
 await single.waitFor();assert.equal(await single.locator('.row-delete-list li').count(),1);
 assert.match(await single.locator('.row-delete-intro').innerText(),/原始素材.*生成历史.*保留/);
 await single.getByRole('button',{name:'删除类型',exact:true}).click();
 state=await wait(s=>s.rows.length===2);assert.deepEqual(state.rows.map(row=>row.name),['保留任务','隐藏任务']);
 assert.equal(await page.getByLabel('用户要求',{exact:true}).inputValue(),'未保存但需要保留的要求');
 await page.getByRole('button',{name:'清除筛选',exact:true}).click();
 await page.getByTestId('delete-rows').click();
 const multiple=page.getByRole('dialog',{name:'批量删除素材类型',exact:true});await multiple.waitFor();
 assert.equal(await multiple.locator('.row-delete-list li').count(),2);
 assert.match(await multiple.locator('.row-delete-warning').innerText(),/1 行.*尚未保存/);
 await multiple.getByRole('button',{name:'取消',exact:true}).click();
 assert.equal((await call('getState')).rows.length,2);
 await page.getByTestId('delete-rows').click();await multiple.getByRole('button',{name:'删除这 2 个类型',exact:true}).click();
 await wait(s=>s.rows.length===0);
 await page.getByTestId('add-row').click();state=await wait(s=>s.rows.length===1);assert.equal(state.rows[0].code,'A01');
 await page.screenshot({path:path.join(out,'image-row-operations.png')});
 await application.close();application=await launch();page=await application.firstWindow();
 await page.getByTestId('add-row').waitFor();state=await call('getState');assert.equal(state.rows.length,1);assert.equal(state.rows[0].code,'A01');
 assert.deepEqual(errors,[]);
 await fs.writeFile(path.join(out,'result.json'),JSON.stringify({passed:true,tests:['A01 default','B01→B02→B03','filtered selection deletion','retain unrelated unsaved configuration','target dirty confirmation','cancel keeps rows','delete all and restart'],errors},null,2));
 console.log('IMAGE_ROWS_UI_PASS',out);
}finally{await application.close();}
